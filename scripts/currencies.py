#!/usr/bin/env python3
"""Generate src/glecimal/currency.gleam from the ISO 4217 list.

scripts/iso-4217.tsv pins the list as the maintenance agency (SIX) published
it; only currencies with minor units are kept, since an amount needs a scale.
The table only grows: a code that leaves the list stays, marked with the date
of the first list without it, so records written with it still read back. Its
constant is deprecated and `from_code` still accepts it. A change in a code's
minor units changes amounts, so --refresh reports it: that is a major release.

    scripts/currencies.py             regenerate currency.gleam from the TSV
    scripts/currencies.py --check     fail if currency.gleam differs
    scripts/currencies.py --refresh   download the current list into the TSV
"""

import subprocess
import sys
import urllib.request
import xml.etree.ElementTree as ElementTree
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "scripts" / "iso-4217.tsv"
OUTPUT = ROOT / "src" / "glecimal" / "currency.gleam"
SOURCE = (
    "https://www.six-group.com/dam/download/financial-information/"
    "data-center/iso-currrency/lists/list-one.xml"
)
GLEAM_KEYWORDS = {
    "as", "assert", "auto", "case", "const", "delegate", "derive", "echo",
    "else", "fn", "if", "implement", "import", "let", "macro", "opaque",
    "panic", "pub", "test", "todo", "type", "use",
}
FUNCTIONS = {"from_code", "listed", "code", "numeric_code", "minor_units", "name"}


def refresh() -> None:
    with urllib.request.urlopen(SOURCE, timeout=30) as response:
        root = ElementTree.fromstring(response.read())
    published = root.attrib["Pblshd"]
    rows = {}
    for entry in root.iter("CcyNtry"):
        code = entry.findtext("Ccy")
        units = entry.findtext("CcyMnrUnts")
        if code and units and units.isdigit() and code not in rows:
            rows[code] = [entry.findtext("CcyNbr"), units, entry.findtext("CcyNm").strip(), "-"]
    if TABLE.exists():
        for code, number, units, name, withdrawn in read_table()[1]:
            if code not in rows:
                rows[code] = [number, units, name, published if withdrawn == "-" else withdrawn]
                print(f"{code} left the list: kept as withdrawn {rows[code][3]}")
            elif rows[code][1] != units:
                print(f"{code} minor units changed {units} -> {rows[code][1]}: a major release")
    lines = [f"# ISO 4217, published {published}, from {SOURCE}"]
    lines += ["\t".join((code, *rows[code])) for code in sorted(rows)]
    TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} currencies published {published} to {TABLE}")


def read_table() -> tuple:
    """The publication date and the rows: code, numeric code, minor units,
    name, and "-" or the date of the first list without the code."""
    header, *rows = TABLE.read_text(encoding="utf-8").splitlines()
    published = header.split("published ")[1].split(",")[0]
    return published, [row.split("\t") for row in rows]


def render() -> str:
    published, rows = read_table()
    current = [row for row in rows if row[4] == "-"]
    out = [
        f"//// The ISO 4217 currencies that have minor units, as the maintenance",
        f"//// agency (SIX) published them on {published}: {len(current)} codes.",
        "////",
        "//// A constant is the code in lower case: `currency.brl`. The table only",
        "//// grows: a code withdrawn from ISO 4217 keeps a deprecated constant and",
        "//// `from_code` still reads it, so old records read back.",
        "////",
        "//// Generated by scripts/currencies.py from scripts/iso-4217.tsv; do not",
        "//// edit.",
        "",
        "/// A currency: its alphabetic and numeric codes, the number of digits",
        "/// after the point in its amounts, and its English name.",
        "pub opaque type Currency {",
        "  Currency(code: String, numeric_code: Int, minor_units: Int, name: String)",
        "}",
        "",
        "/// The publication date of the list these constants follow.",
        f'pub const iso_4217_published = "{published}"',
        "",
    ]
    literals = {}
    for code, number, units, name, withdrawn in rows:
        constant = code.lower()
        if constant in GLEAM_KEYWORDS or constant in FUNCTIONS:
            raise SystemExit(f"{code} clashes with a Gleam keyword or function")
        escaped = name.replace("\\", "\\\\").replace('"', '\\"')
        literals[code] = (
            f'Currency(code: "{code}", numeric_code: {int(number)}, '
            f'minor_units: {units}, name: "{escaped}")'
        )
        out.append(f"/// {name} ({code}, {number}): {units} minor units.")
        if withdrawn != "-":
            out.append(f'@deprecated("{code} left ISO 4217 in the list of {withdrawn}")')
        out += [f"pub const {constant} = {literals[code]}", ""]
    out += [
        "/// The currency with this alphabetic code, in upper case as ISO 4217",
        "/// writes it, withdrawn codes included.",
        "pub fn from_code(code: String) -> Result(Currency, Nil) {",
        "  case code {",
    ]
    for code, *_, withdrawn in rows:
        value = code.lower() if withdrawn == "-" else literals[code]
        out.append(f'    "{code}" -> Ok({value})')
    out += [
        "    _ -> Error(Nil)",
        "  }",
        "}",
        "",
        "/// Every currency in the current list, by code.",
        "pub fn listed() -> List(Currency) {",
        "  [",
    ]
    out += [f"    {code.lower()}," for code, *_ in current]
    out += [
        "  ]",
        "}",
        "",
        "/// The alphabetic code, such as `BRL`.",
        "pub fn code(currency: Currency) -> String {",
        "  currency.code",
        "}",
        "",
        "/// The numeric code, such as 986 for `BRL`.",
        "pub fn numeric_code(currency: Currency) -> Int {",
        "  currency.numeric_code",
        "}",
        "",
        "/// The digits after the point in an amount: 2 for `BRL`, 0 for `JPY`.",
        "pub fn minor_units(currency: Currency) -> Int {",
        "  currency.minor_units",
        "}",
        "",
        "/// The English name, such as `Brazilian Real`.",
        "pub fn name(currency: Currency) -> String {",
        "  currency.name",
        "}",
    ]
    return formatted("\n".join(out) + "\n")


def formatted(source: str) -> str:
    """The source as `gleam format` writes it, so the check compares like
    with like."""
    return subprocess.run(
        ["gleam", "format", "--stdin"], input=source, capture_output=True,
        text=True, check=True,
    ).stdout


def main() -> int:
    if sys.argv[1:] == ["--refresh"]:
        refresh()
    rendered = render()
    if sys.argv[1:] == ["--check"]:
        if OUTPUT.read_text(encoding="utf-8") != rendered:
            print(f"{OUTPUT} is stale: run scripts/currencies.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
